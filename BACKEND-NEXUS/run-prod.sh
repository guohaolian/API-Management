#!/usr/bin/env bash
# 生产环境启动脚本（示例）。

# 开启严格模式：遇错即停、未声明变量视为错误、管道错误向上传递
set -euo pipefail

# 启动应用的运行命令（生产模式）：
# - `uv run robyn`：使用项目的运行器/管理工具运行名为 robyn 的运行器（取决于项目依赖）
# - `-m app`：指定被加载的 Python 模块/入口为 `app`（通常包含应用实例）
# - `--process=4`：启用进程级并发（例如多进程模式），可根据 CPU 核心数和负载调整
# - `--workers=3`：在每个进程内启用的工作线程/子进程数量（取决于运行器的并发模型）
#
# 注意：
# - 生产环境通常建议使用进程管理器（systemd / supervisord /容器编排）来管理这些进程并处理重启、日志、健康检查等。
# - 在将此脚本用于生产前，请确认 `uv` 命令含义与参数（`--process`、`--workers`）与实际运行器版本一致。
uv run robyn -m app --process=4 --workers=3