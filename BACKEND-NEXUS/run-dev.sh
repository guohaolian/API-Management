#!/usr/bin/env bash
# 脚本：用于在开发环境下启动应用的本地运行命令

# 严格模式：
# -e: 遇到任意命令返回非 0 值时立即退出（避免隐藏错误）
# -u: 将未设置的变量视为错误并退出（避免拼写或未初始化变量导致不确定行为）
# -o pipefail: 当管道中任意一段失败时，整个管道返回失败码（默认只返回最后一段的返回码）
set -euo pipefail

# 启动开发服务器的命令（项目依赖的运行器）
# 注意：
# - `uv`：项目中用于启动服务的 CLI 工具，需在虚拟环境或系统 PATH 中可用（例如某些项目使用 uvicorn 或自定义 wrapper）。
# - `run robyn`：表示使用 uv 的 run 子命令启动名为 robyn 的运行器/应用（取决于具体项目依赖）。
# - `-m app`：指定要加载的 Python 模块/入口名为 `app`（通常项目根目录下有 app.py 或包 app 用作应用入口）。
# - `--dev`：以开发模式启动（通常启用自动重载、调试日志等），上线请使用相应的生产命令或配置。
uv run robyn -m app --dev